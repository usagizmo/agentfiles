// check-emphasis の判定テスト。`bun test` で走る。
//
// **見逃しと誤検知を両方押さえる。**この検査は commit 前の gate ではなく docs skill の
// 品質パスから呼ばれるので、誤検知を出すと「gate が常時赤で新しい違反が埋もれる」側へ倒れる。

import { expect, test } from "bun:test";
import { brokenLines } from "../agents/skills/docs/scripts/check-emphasis.ts";

const at = (src: string) => brokenLines(src).map((l) => l.no);

// --- 壊れている（検出しなければならない） --------------------------------

test("閉じ側: 直前が約物・直後が通常文字だと閉じ記号にならない", () => {
  expect(at("**これは。**続く文")).toEqual([1]);
});

test("開き側: 直後が約物・直前が通常文字だと開き記号にならない", () => {
  expect(at("文字は**「約物」**です")).toEqual([1]);
});

test("ソフトブレークをまたぐ 1 組でも、壊れていれば両端を挙げる", () => {
  expect(at("読む側は**「まだ」と\n「作れない」を区別できない。**")).toEqual([1, 2]);
});

test("マーカーが偶数個でリテラルが残らなくても、範囲がずれていれば挙げる", () => {
  // `**A。**B**C**` は閉じ損ねた `**` が次の開きを拾って入れ子になる。
  // リテラルの `**` が 1 つも残らないので、残骸を数える検査では素通りする。
  expect(at("**規則。**理由の説明。そこは**しない**。")).toEqual([1]);
});

test("入れ子は隣り合う 2 つの強調と区別する", () => {
  // `**A**。**B**` は正しい並び。誤検知すると gate が常時赤になる。
  expect(at("**規則**。**別の規則**。")).toEqual([]);
});

test("斜体の入れ子も落とす", () => {
  expect(at("これは*前。*続き*後*です")).toEqual([1]);
});

test("太字の中の斜体は通す", () => {
  expect(at("これは**太字に *斜体* を含む**文")).toEqual([]);
});

test("閉じずに段落が終わったら壊れている", () => {
  expect(at("**開いたまま終わる")).toEqual([1]);
});

// --- 壊れていない（誤検知してはならない） --------------------------------

test("行末の約物 + 閉じは成立する", () => {
  expect(at("**これは行末。**")).toEqual([]);
});

test("約物の外に出した強調は成立する", () => {
  expect(at("**強調**。普通の文")).toEqual([]);
});

// characterization: 自前で flanking を判定していた頃、コードスパンをバッククォートごと
// 伏せて壊した形。marked 版では最初から通るので回帰テストではない（外しても落ちない）。
test("閉じの直後がコードスパンでも成立する", () => {
  expect(at("**指紋。**`resolve` と対になる")).toEqual([]);
});

// 回帰: 規約そのものを説明する文には `**` が逐語で出てくる。
// 描画結果の <code> を除かずに ** を数えると、この行を壊れていると言う。
test("コードスパンの中の ** は数えない", () => {
  expect(at("- **行頭の `**` 装飾は許容する**（`**Depends on #N**`）")).toEqual([]);
});

// 回帰: 空行だけで切ると、別々のリスト項目の未対応どうしが対応して見逃す
test("別々のリスト項目の ** は対応しない", () => {
  expect(at("- **壊れた。\n- 別項目**")).toEqual([1, 2]);
});

test("表のセルをまたいで対応しない", () => {
  expect(at("| a | b |\n| --- | --- |\n| **壊れた | x |\n| 別行** | y |")).toEqual([3, 4]);
});

// 区切り行が無ければ表にならず段落になる。段落なら 2 行で 1 組が成立するので壊れていない
test("表に見えても段落なら、実際に太字になるので違反ではない", () => {
  expect(at("| **これは | b |\n| 段落** | d |")).toEqual([]);
});

test("見出しと本文をまたいで対応しない", () => {
  expect(at("## **壊れた\n本文**")).toEqual([1, 2]);
});

// 回帰: 描画結果に残る HTML コメント / 属性値の ** を数えない
test("HTML コメントの中の ** は数えない", () => {
  expect(at("本文 <!-- ** --> の続き")).toEqual([]);
});

test("属性値の中の ** は数えない", () => {
  expect(at('<span data-x="**">値</span>')).toEqual([]);
});

// 回帰: fence は開いた長さ以上でしか閉じない
test("4 バッククォートの fence は 3 個では閉じない", () => {
  expect(at("````\n```\n**壊れた例。**続く文\n````")).toEqual([]);
});

test("字下げコードブロックは本文ではない", () => {
  expect(at("段落。\n\n    **壊れた例。**続く文\n")).toEqual([]);
});

test("フェンスの中は本文ではない", () => {
  expect(at("```markdown\n**壊れた例。**続く文\n```")).toEqual([]);
});

test("チルダのフェンスも同じ", () => {
  expect(at("~~~\n**壊れた例。**続く文\n~~~")).toEqual([]);
});

test("表のセル内の強調", () => {
  expect(at("| a | b |\n| --- | --- |\n| **強調** | 値 |")).toEqual([]);
});

test("リスト項目の強調", () => {
  expect(at("- **項目**: 説明\n- **項目**: 説明")).toEqual([]);
});

test("半角スペースで逃がした形は成立する", () => {
  expect(at("読む側は **「まだ」と「作れない」を区別できない。**")).toEqual([]);
});

test("強調が無ければ何も出ない", () => {
  expect(at("ただの文。\n\n次の段落。")).toEqual([]);
});

// --- 位置 -----------------------------------------------------------------

test("行番号は空行とフェンスを跨いでも実ファイルの位置を指す", () => {
  const src = ["# 見出し", "", "```", "code", "```", "", "壊れる**「ここ」**行"].join("\n");
  expect(at(src)).toEqual([7]);
});
